function ansi(variant: Variant) {
  const entries = variant.ansi.map((color, index) => {
    const name = AnsiNames[index % AnsiNames.length];
    return [`terminal.ansi${index < AnsiNames.length ? '' : 'Bright'}${name}`, color];
  });
  return Object.fromEntries(entries);
}

function symbolIcons(variant: Variant) {
  const entries = SymbolIcons.flatMap(({ role, names }) =>
    names.map((name) => [`symbolIcon.${name}Foreground`, variant[role]]),
  );
  return Object.fromEntries(entries);
}

