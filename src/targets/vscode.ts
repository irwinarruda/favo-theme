function tokenColors(variant: Variant) {
  return Object.entries(Tokens).map(([name, { role, font, scopes }]) => ({
    name,
    scope: scopes,
    settings: { foreground: variant[role], ...font },
  }));
}

function semanticTokenColors(variant: Variant) {
  const entries = Object.values(SemanticTokens).flatMap(({ role, font, selectors }) =>
    selectors.map((selector) => [selector, { foreground: variant[role], ...font }]),
  );
  return Object.fromEntries(entries);
}

export function vscode(variant: Variant): Output {
  const theme = {
    $schema: 'vscode://schemas/color-theme',
    name: variant.name,
    type: variant.appearance,
    semanticHighlighting: true,
    colors: colors(variant),
    tokenColors: tokenColors(variant),
    semanticTokenColors: semanticTokenColors(variant),
  };
  return { path: `vscode/themes/favo-${variant.id}.json`, text: `${JSON.stringify(theme, undefined, 2)}\n` };
}
