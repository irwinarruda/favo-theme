import { tints } from '../color';
import type { Output, Variant } from '../palette';

export function opencode(variant: Variant): Output {
  const { diffAdded, diffRemoved } = tints(variant);
  const defs = {
    accentText: variant.accentText,
    background: variant.background,
    border: variant.border,
    comment: variant.comment,
    constant: variant.constant,
    diffAddedBackground: diffAdded,
    diffRemovedBackground: diffRemoved,
    float: variant.float,
    foreground: variant.foreground,
    function: variant.function,
    keyword: variant.keyword,
    panel: variant.panel,
    param: variant.param,
    raised: variant.raised,
    regex: variant.regex,
    string: variant.string,
    type: variant.type,
    warning: variant.warning,
  };
  const roles = {
    primary: 'accentText',
    secondary: 'param',
    accent: 'type',
    error: 'regex',
    warning: 'warning',
    success: 'string',
    info: 'function',
    text: 'foreground',
    textMuted: 'comment',
    background: 'background',
    backgroundPanel: 'panel',
    backgroundElement: 'raised',
    border: 'border',
    borderActive: 'accentText',
    borderSubtle: 'float',
    diffAdded: 'string',
    diffRemoved: 'regex',
    diffContext: 'comment',
    diffHunkHeader: 'comment',
    diffHighlightAdded: 'string',
    diffHighlightRemoved: 'regex',
    diffAddedBg: 'diffAddedBackground',
    diffRemovedBg: 'diffRemovedBackground',
    diffContextBg: 'panel',
    diffLineNumber: 'comment',
    diffAddedLineNumberBg: 'diffAddedBackground',
    diffRemovedLineNumberBg: 'diffRemovedBackground',
    markdownText: 'foreground',
    markdownHeading: 'accentText',
    markdownLink: 'function',
    markdownLinkText: 'param',
    markdownCode: 'string',
    markdownBlockQuote: 'comment',
    markdownEmph: 'constant',
    markdownStrong: 'keyword',
    markdownHorizontalRule: 'comment',
    markdownListItem: 'accentText',
    markdownListEnumeration: 'type',
    markdownImage: 'function',
    markdownImageText: 'param',
    markdownCodeBlock: 'foreground',
    syntaxComment: 'comment',
    syntaxKeyword: 'keyword',
    syntaxFunction: 'function',
    syntaxVariable: 'foreground',
    syntaxString: 'string',
    syntaxNumber: 'constant',
    syntaxType: 'type',
    syntaxOperator: 'keyword',
    syntaxPunctuation: 'foreground',
  };
  const theme = Object.fromEntries(Object.entries(roles).map(([key, def]) => [key, { dark: def, light: def }]));
  const file = { $schema: 'https://opencode.ai/theme.json', defs, theme };
  return { path: `opencode/favo-${variant.id}.json`, text: `${JSON.stringify(file, undefined, 2)}\n` };
}
