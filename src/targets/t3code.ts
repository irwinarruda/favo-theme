import { mix } from '../color';
import type { Output, Variant } from '../palette';

export function t3code(variant: Variant): Output {
  const { accent, background, comment, fill, faint, foreground, onFill, panel, raised, regex, selection, warning } =
    variant;
  const colors = {
    canvas: background,
    chrome: panel,
    toolbar: panel,
    toolbarForeground: foreground,
    toolbarBorder: variant.border,
    toolbarControl: raised,
    toolbarControlForeground: foreground,
    toolbarControlHover: mix(accent, raised, 0.12),
    surface: panel,
    surfaceRaised: raised,
    surfaceOverlay: raised,
    text: foreground,
    textMuted: comment,
    border: variant.border,
    input: variant.border,
    focus: accent,
    accent: fill,
    accentForeground: onFill,
    secondary: raised,
    secondaryForeground: foreground,
    muted: panel,
    mutedForeground: comment,
    placeholder: comment,
    secondaryLabel: comment,
    iconMuted: comment,
    error: regex,
    errorForeground: regex,
    errorSurface: mix(regex, background, 0.14),
    warning,
    warningForeground: warning,
    warningSurface: mix(warning, background, 0.14),
    update: fill,
    updateForeground: onFill,
    updateSurface: mix(accent, background, 0.18),
    accentSurface: mix(accent, background, 0.14),
    accentSurfaceForeground: foreground,
    messageSurface: raised,
    messageForeground: foreground,
    messageAction: fill,
    messageActionForeground: onFill,
    messageActionHover: variant.fillHover,
    codeBackground: variant.appearance === 'dark' ? variant.float : panel,
    codeForeground: foreground,
    searchMatchBackground: selection,
    searchMatchForeground: foreground,
    searchMatchActiveBackground: fill,
    searchMatchActiveForeground: onFill,
    sidebar: panel,
    sidebarForeground: foreground,
    sidebarMutedForeground: comment,
    sidebarControlSurface: raised,
    sidebarRowHover: mix(foreground, panel, 0.05),
    sidebarRowActive: mix(accent, panel, 0.12),
    sidebarRowSelected: mix(accent, panel, 0.18),
    sidebarBorder: variant.border,
    terminalBackground: background,
    terminalForeground: foreground,
    terminalCursor: accent,
    terminalSelection: selection,
    terminalScrollbar: faint,
    terminalScrollbarHover: comment,
  };
  const theme = { version: 1, name: variant.name, appearance: variant.appearance, colors };
  return { path: `t3code/favo-${variant.id}.json`, text: `${JSON.stringify(theme, undefined, 2)}\n` };
}
